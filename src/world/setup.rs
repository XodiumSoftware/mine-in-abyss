//! Worlds for `mine-in-abyss`.
//!
//! Each layer of the Abyss lives in its own Minecraft world, so players physically
//! descend by moving between worlds. This module is responsible for creating (or
//! re-attaching to) those worlds on startup.
//!
//! Every layer world is **generated empty** by the `Void` chunk generator
//! (`world::generator`). The Abyss is a vertical world built from authored maps, so a world
//! that has no map yet must not arrive with terrain of its own: an empty world is a blank
//! canvas, whereas a default world would seed terrain that then competes with the map.
//!
//! The layer worlds share a clock, copied from [`First`](crate::Layer::First) by
//! `world::clock`, so descending never makes the sun jump.
//!
//! World names come from [`Layer::world`](crate::layer::Layer::world) and are
//! stable across releases: they are derived from the layer's ordinal, not its display
//! name.

use super::generator::Void;
use crate::layer::Layer;
use pumpkin_plugin_api::worldgen::GeneratorManager;
use pumpkin_plugin_api::{Context, Dimension, Server, World};
use std::cell::RefCell;
use std::collections::HashSet;
use tracing::{info, warn};

thread_local! {
    /// World names created (or attached to) by [`Worlds::setup`].
    ///
    /// Only the set of ready world names is cached; the `World` handle itself is a
    /// non-cloneable resource, so it is re-resolved from the server on demand.
    static READY: RefCell<HashSet<String>> = RefCell::new(HashSet::new());
}

/// Creates and tracks one Minecraft world per layer.
///
/// Worlds are created once during plugin load and kept for the lifetime of the server.
#[derive(Debug, Clone, Copy, Default)]
pub struct Worlds;

impl Worlds {
    /// Creates a world for every layer in `layers` and remembers it.
    ///
    /// Each world is given the `Void` chunk generator (`world::generator`), so
    /// the first chunk it ever generates is empty. The generator is attached before the world
    /// is used, so there is no window in which a chunk could be generated by the default
    /// generator; a world that already has chunks keeps them, which is what makes an
    /// authored map safe across restarts.
    ///
    /// Safe to call more than once: existing worlds are re-attached rather than
    /// duplicated, and a failure for one layer does not stop the others. Each layer's
    /// [`Layer::game_rules`] are applied every time, so they cannot be lost to a world
    /// folder that was saved with different rules.
    ///
    /// Returns the number of worlds that are available after the call.
    pub fn setup(context: &Context, layers: &[Layer]) -> usize {
        let server = context.get_server();
        let generator = GeneratorManager::register(Void);

        for layer in layers {
            let name = layer.world();
            let world = server.create_world(&name, Dimension::Overworld);

            if server.has_world(&name) {
                world.set_chunk_generator(generator);

                for &(rule, value) in layer.game_rules() {
                    world.set_game_rule(rule, value);
                }

                info!("World '{name}' ready for {}", layer.name());
                READY.with(|r| r.borrow_mut().insert(name.clone()));
            } else {
                warn!("World '{name}' was not created for {}", layer.name());
            }
        }

        let count = READY.with(|r| r.borrow().len());
        info!("Worlds: {count} layer world(s) available");
        count
    }

    /// Returns whether the world called `name` was made available by [`Worlds::setup`].
    #[must_use]
    pub fn is_ready(name: &str) -> bool {
        READY.with(|r| r.borrow().contains(name))
    }

    /// Returns the number of worlds currently tracked.
    #[must_use]
    pub fn count() -> usize {
        READY.with(|r| r.borrow().len())
    }

    /// Moves the monsters in `from` down into the layer `to`.
    ///
    /// Entities cannot change layers, so a layer world left behind by a descent takes its
    /// inhabitants with it: without this, a player who steps into the void and lands a layer
    /// down would be followed by nothing, and the monsters they were fighting would simply
    /// cease to exist.
    ///
    /// **Every** monster in `from` is moved, not only the ones chasing the player. Asking a
    /// mob whether it is targeting anyone would mean one AI query per entity, and the point
    /// of the move is that the layer above is emptied of the danger the player escaped: a
    /// monster left behind would be stranded in a world nobody can reach without descending
    /// again.
    ///
    /// Each monster keeps its own X/Z and is placed at `entry_y`, the height the player
    /// arrives at, so it falls into the layer with them rather than appearing on its floor.
    /// It is rescaled for the destination with `Monsters::apply`, so what follows is as
    /// dangerous as the layer it followed the player into.
    ///
    /// Returns how many monsters were moved.
    pub fn descend_monsters(server: &Server, from: &World, to: &World, layer: Layer) -> usize {
        let target_name = to.get_name();
        let mut moved = 0;

        for entity in from.get_entities() {
            let Some(living) = entity.as_living() else {
                continue;
            };

            if !crate::events::monsters::is_monster(entity.get_type()) {
                continue;
            }

            let Some(target) = server.get_world_by_name(&target_name) else {
                break;
            };

            let (x, _, z) = entity.get_position();
            entity.teleport((x, Layer::entry_y(), z), target);
            crate::events::monsters::Monsters::apply(&living, layer);
            moved += 1;
        }

        if moved > 0 {
            info!(
                "Moved {moved} monster(s) from '{}' into '{target_name}' for {}",
                from.get_name(),
                layer.id()
            );
        }

        moved
    }
}
